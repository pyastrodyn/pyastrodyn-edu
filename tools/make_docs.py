def number(value, digits: int = 7) -> str:
    """Format a number with the given number of significant digits."""
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, str):
        return value
    array = np.asarray(value, dtype=float)
    if array.ndim == 0:
        return f"{float(array):.{digits}g}"
    return "[" + ", ".join(f"{x:.{digits}g}" for x in array) + "]"


def freeze():
    results = {p.id: validation.to_plain(p.results()) for p in validation.PROBLEMS}
    EXPECTED.write_text(json.dumps(results, indent=1) + "\n")


