# Colours of the boxes of the library map, one triple per group: (fill, border, text).
MAP_COLOURS = (("#EEEDFE", "#534AB7", "#3C3489"), ("#E1F5EE", "#0F6E56", "#085041"),
               ("#FAEEDA", "#8A5A0B", "#633F06"),
               ("#F1EFE8", "#5F5E5A", "#444441"), ("#F1EFE8", "#5F5E5A", "#444441"))
# A group with no module yet (a release that stops before its lectures) is not shown.
MAP_COLOURS = tuple(colour for (_, modules), colour in zip(GROUPS, MAP_COLOURS) if modules)
GROUPS = tuple(group for group in GROUPS if group[1])
SECTION_TITLES = ("Parameters", "Returns", "References", "Notes", "Examples", "Raises")


def inline(text: str) -> str:
    """Docstring markup to Markdown: ``name`` becomes `name`."""
    return text.replace("``", "`")


def docstring_markdown(doc: str) -> list:
    """Convert a docstring in NumPy style into Markdown lines."""
    lines = inspect.cleandoc(doc).split("\n")
    out, section, k = [], None, 0
    in_code = False
    while k < len(lines):
        line = lines[k]
        is_title = (k + 1 < len(lines) and line.strip() in SECTION_TITLES
                    and set(lines[k + 1].strip()) == {"-"})
        if is_title:
            if in_code:
                out.append("```")
                in_code = False
            section = line.strip()
            out += ["", f"**{section}**", ""]
            k += 2
            continue
        if section == "Examples":
            if line.strip() and not in_code:
                if line.startswith(">>>"):
                    out.append("```python")
                    in_code = True
                    out.append(line)
                else:
                    out.append(inline(line))
            elif in_code and not line.strip():
                out.append("```")
                in_code = False
                out.append("")
            else:
                out.append(line)
        elif section in ("Parameters", "Returns", "Raises"):
            if line.strip() and not line.startswith(" "):
                names, _, kind = line.partition(" : ")
                if kind:
                    item = f"- `{names.strip()}` ({inline(kind.strip())})"
                else:  # a line without a name gives only the type of the result
                    item = "- " + inline(names.strip())
                out.append(item)
            elif line.strip():
                out.append("  " + inline(line.strip()))
            else:
                out.append("")
        else:
            out.append(inline(line))
        k += 1
    if in_code:
        out.append("```")
    return out


def signature_text(name: str, function) -> str:
    """The call of a function with its argument names and default values."""
    parts = []
    for parameter in inspect.signature(function).parameters.values():
        if parameter.name in ("self", "cls"):
            continue
        if parameter.default is inspect.Parameter.empty:
            parts.append(parameter.name)
        else:
            parts.append(f"{parameter.name}={parameter.default!r}")
    return f"{name}({', '.join(parts)})"


def first_sentence(doc: str) -> str:
    """The first paragraph of a docstring, on one line."""
    paragraph = inspect.cleandoc(doc).split("\n\n")[0]
    return inline(" ".join(paragraph.split()))


def uses(module_name: str) -> list:
    """The other modules of the library that a module imports."""
    source = (ROOT / "pyastrodyn_edu" / f"{module_name}.py").read_text()
    found = set(re.findall(r"^from \.(\w+) import", source, flags=re.M))
    block = re.search(r"^from \. import \(?([^)]*?)\)?$", source, flags=re.M | re.S)
    if block:
        found |= set(re.findall(r"\w+", block.group(1)))
    return sorted(name for name in found if not name.startswith("_") and name != "constants")


def constants_table() -> list:
    """One row per constant, with the comment written above it in the source."""
    source = (ROOT / "pyastrodyn_edu" / "constants.py").read_text().split("\n")
    constants = importlib.import_module("pyastrodyn_edu.constants")
    rows = ["| Name | Value | Meaning and source |", "|---|---|---|"]
    for name in constants.__all__:
        k = next(n for n, line in enumerate(source) if line.startswith(name + " ="))
        comment = []
        while k > 0 and source[k - 1].startswith("#"):
            k -= 1
            comment.insert(0, source[k].lstrip("# ").strip())
        rows.append(f"| `{name}` | {getattr(constants, name):.10g} | {' '.join(comment)} |")
    return rows


def module_count(name: str) -> str:
    """What a module contains, in two or three words."""
    module = importlib.import_module(f"pyastrodyn_edu.{name}")
    if name == "constants":
        return f"{len(module.__all__)} constants"
    if name == "units":
        return "1 class"
    if name == "validation":
        return f"{len(module.PROBLEMS)} problems"
    return f"{sum(inspect.isfunction(getattr(module, n)) for n in module.__all__)} functions"


def library_map_svg() -> str:
    """The block diagram of the library: one box per module, grouped as in GROUPS."""
    width, margin, pad, per_row = 680, 20, 20, 4
    box_w, box_h, gap, label_h = 135, 72, 20, 36
    font = 'font-family="Helvetica, Arial, sans-serif"'
    parts, y = [], margin
    for (group, modules), (fill, border, text) in zip(GROUPS, MAP_COLOURS):
        rows = -(-len(modules) // per_row)
        height = label_h + rows * box_h + (rows - 1) * gap + pad
        parts.append(f'<rect x="{margin}" y="{y}" width="{width - 2 * margin}" height="{height}" rx="10" '
                     f'fill="none" stroke="#888780" stroke-dasharray="5 4"/>')
        parts.append(f'<text x="{margin + pad}" y="{y + 24}" {font} font-size="14" font-weight="bold" '
                     f'fill="#2C2C2A">{group}</text>')
        for k, (name, where) in enumerate(modules):
            x = margin + pad + (k % per_row) * (box_w + gap)
            top = y + label_h + (k // per_row) * (box_h + gap)
            centre = x + box_w / 2
            short = where if len(where) <= 20 else where.split(",")[0]
            short = {"single_state": "One-state versions", "validation": "Worked problems"}.get(name, short)
            parts.append(f'<rect x="{x}" y="{top}" width="{box_w}" height="{box_h}" rx="8" '
                         f'fill="{fill}" stroke="{border}"/>')
            parts.append(f'<text x="{centre}" y="{top + 25}" text-anchor="middle" {font} font-size="14" '
                         f'font-weight="bold" fill="{text}">{name}</text>')
            parts.append(f'<text x="{centre}" y="{top + 44}" text-anchor="middle" {font} font-size="12" '
                         f'fill="{border}">{short}</text>')
            parts.append(f'<text x="{centre}" y="{top + 60}" text-anchor="middle" {font} font-size="12" '
                         f'fill="{border}">{module_count(name)}</text>')
        y += height + 16
    total = y - 16 + margin
    head = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {total}" width="{width}" '
            f'height="{total}" role="img">\n<title>Map of the modules of PyAstroDyn-edu</title>\n'
            f'<rect width="{width}" height="{total}" fill="#FFFFFF"/>\n')
    return head + "\n".join(parts) + "\n</svg>\n"


def library_map_html() -> list:
    """The block diagram as a grid of boxes; the name in each box is a link.

    A picture shown inside a Markdown file cannot contain links, so inside
    ``functions.md`` the diagram is written as tables. The picture
    ``library_map.svg`` shows the same boxes, for slides and other documents.
    """
    per_row = 4
    lines = []
    for group, modules in GROUPS:
        lines += ["<table>", f'<tr><th colspan="{per_row}" align="left">{group}</th></tr>']
        for start in range(0, len(modules), per_row):
            lines.append("<tr>")
            for name, where in modules[start:start + per_row]:
                lines.append(f'<td align="center" width="170"><a href="#{name}"><b>{name}</b></a><br>'
                             f"{where}<br>{module_count(name)}</td>")
            for _ in range(per_row - len(modules[start:start + per_row])):
                lines.append('<td width="170"></td>')  # empty box: keeps the columns aligned
            lines.append("</tr>")
        lines += ["</table>", ""]
    return lines


def functions_document() -> str:
    lines = [
        "# Function guide",
        "",
        "Every module of the library and every function in it: what it computes,",
        "its inputs and outputs, the books and the lecture it comes from, and its",
        "limits of validity.",
        "",
        "This file is generated by `tools/make_docs.py` from the documentation",
        "written inside the code (the docstrings). Do not edit it by hand. The same",
        "text appears in VS Code when the mouse rests on the name of a function,",
        "and in a notebook with a question mark after the name, for example",
        "`ad.coe2rv?`.",
        "",
        "Conventions used throughout (see the README): `mu` is always passed",
        "explicitly; angles are in radians; any consistent set of units may be",
        "used; a vector has shape (3,) for one state or (n, 3) for n states, and",
        "its name ends with the letter of its basis, as in `r_N`.",
        "",
        "## Map of the library",
        "",
        "One file per module, in the folder `pyastrodyn_edu`. Each box is a module.",
        "Click the name in a box to go to the list of its functions; every list",
        "ends with a link back to this map.",
        "",
    ]
    lines += library_map_html()
    lines += [
        "The same map as a picture, for slides: `docs/library_map.svg`.",
        "",
        "Which modules each one uses:",
        "",
        "| Group | Module | Taught in, or purpose | Functions | Uses the modules |",
        "|---|---|---|---|---|",
    ]
    for group, modules in GROUPS:
        for name, where in modules:
            module = importlib.import_module(f"pyastrodyn_edu.{name}")
            if name == "constants":
                count = f"{len(module.__all__)} constants"
            elif name == "units":
                count = "1 class"
            else:
                count = str(sum(inspect.isfunction(getattr(module, n)) for n in module.__all__))
            used = ", ".join(f"`{u}`" for u in uses(name)) or "none"
            if name == "validation":
                used = "all the computing modules"
            lines.append(f"| {group} | [`{name}`](#{name}) | {where} | {count} | {used} |")
    for group, modules in GROUPS:
        for name, where in modules:
            module = importlib.import_module(f"pyastrodyn_edu.{name}")
            lines += ["", "---", "", f"## {name}", "",
                      f"File `pyastrodyn_edu/{name}.py`. {where}. [Back to the map](#map-of-the-library).", ""]
            lines += docstring_markdown(module.__doc__)
            lines.append("")
            if name == "constants":
                lines += constants_table()
                continue
            members = [(n, getattr(module, n)) for n in module.__all__]
            functions = [(n, f) for n, f in members if inspect.isfunction(f)]
            classes = [(n, c) for n, c in members if inspect.isclass(c)]
            if functions:
                lines += ["| Function | What it does |", "|---|---|"]
                lines += [f"| [`{n}`](#{n.lower()}) | {first_sentence(f.__doc__)} |" for n, f in functions]
            for n, c in classes:
                lines += ["", f"### {n}", "", f"Class. Created with `{signature_text(n, c)}`.", ""]
                lines += docstring_markdown(c.__doc__)
                for method_name, method in vars(c).items():
                    target = getattr(method, "__func__", method)
                    if method_name.startswith("_") or not inspect.isfunction(target) or not target.__doc__:
                        continue
                    lines += ["", f"#### {n}.{method_name}", "",
                              f"`{signature_text(n + '.' + method_name, target)}`", ""]
                    lines += docstring_markdown(target.__doc__)
            for n, f in functions:
                lines += ["", f"### {n}", "", f"`{signature_text(n, f)}`", ""]
                lines += docstring_markdown(f.__doc__)
    text = "\n".join(lines)
    return re.sub(r"\n{3,}", "\n\n", text) + "\n"


