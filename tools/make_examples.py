"""Make the notebook of every example problem from its script.

Each example problem is written once, as a Python script divided into cells:

    # %% [markdown]      starts a cell of text (every line begins with "# ")
    # %%                 starts a cell of code

This tool writes, next to each script ``examples/lectureNN/example_*.py``,
the notebook with the same name and the same cells. Run it from the
repository root after changing a script:

    python tools/make_examples.py

The notebooks are stored without results: run them to see the results.
The tool also writes the list of all examples, ``examples/README.md``.
"""

from pathlib import Path

import nbformat

ROOT = Path(__file__).resolve().parents[1]
MARK_TEXT = "# %% [markdown]"
MARK_CODE = "# %%"


def scripts() -> list:
    """The scripts of all example problems, in order."""
    return sorted((ROOT / "examples").glob("lecture*/example_*.py"))


def cells(source: str) -> list:
    """Split a script into its cells: a list of (kind, text)."""
    found, kind, lines = [], None, []
    for line in source.split("\n") + [MARK_CODE]:      # the added mark closes the last cell
        if line.startswith(MARK_CODE):
            if kind is not None:
                text = "\n".join(lines).strip("\n")
                if text:
                    found.append((kind, text))
            kind = "markdown" if line.startswith(MARK_TEXT) else "code"
            lines = []
        elif kind == "markdown":
            lines.append(line[2:] if line.startswith("# ") else line.lstrip("#"))
        elif kind == "code":
            lines.append(line)
    return found


def notebook(source: str):
    """The notebook with the cells of a script."""
    book = nbformat.v4.new_notebook()
    book.metadata["kernelspec"] = {"display_name": "Python 3", "language": "python", "name": "python3"}
    book.metadata["language_info"] = {"name": "python"}
    for number, (kind, text) in enumerate(cells(source)):
        make = nbformat.v4.new_markdown_cell if kind == "markdown" else nbformat.v4.new_code_cell
        cell = make(text)
        cell["id"] = f"cell-{number:02d}"               # fixed names: the file does not change between runs
        book.cells.append(cell)
    return book


def notebook_text(script: Path) -> str:
    """The content of the notebook file that belongs to a script."""
    return nbformat.writes(notebook(script.read_text()), version=4) + "\n"


def index_text() -> str:
    """The list of all example problems, ``examples/README.md``."""
    from pyastrodyn_edu import validation

    lines = [
        "# Example problems",
        "",
        "Each example problem is worked out step by step in two forms with the same",
        "content: a notebook (`.ipynb`), to experiment with the data, and a script",
        "(`.py`), to read the solution as ordinary Python. How to use them: Step 11",
        "of `docs/getting_started.md`. Statements and results of all the problems:",
        "`docs/problems.md`.",
        "",
        "This file is generated by `tools/make_examples.py`. Do not edit it by hand.",
        "",
        "| Example problem | Title | Files (`.ipynb` and `.py`) |",
        "|---|---|---|",
    ]
    for problem in validation.PROBLEMS:
        number = problem.id[1:].replace("-", ".")                     # "L4-1" -> "4.1"
        found = [s for s in scripts() if s.name.startswith(f"example_{number.replace('.', '_')}_")]
        where = f"`{found[0].parent.name}/{found[0].stem}`" if found else "not yet written"
        lines.append(f"| {number} | {problem.title} | {where} |")
    lines += ["", "Also in this folder: `first_steps.py`, a short script to check the installation",
              "(Step 9 of the guide)."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    for script in scripts():
        script.with_suffix(".ipynb").write_text(notebook_text(script))
        print("written:", script.with_suffix(".ipynb").relative_to(ROOT))
    (ROOT / "examples" / "README.md").write_text(index_text())
    print("written: examples/README.md")
